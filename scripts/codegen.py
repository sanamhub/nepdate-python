"""Generate the committed, derived files from the read-only shared data.

Standard library only, so it runs wherever Python runs. Plain invocation regenerates every
derived file. ``--check`` exits 1 when any derived file differs from what this script would
write; the CI gate runs it that way.
"""

from __future__ import annotations

import argparse
import datetime
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
CALENDAR_JSON = ROOT / "shared" / "data" / "calendar" / "bs-calendar.json"
CALENDAR_PY = ROOT / "src" / "nepdate" / "_calendar.py"
ROOT_LICENSE = ROOT / "LICENSE"
ROOT_NOTICE = ROOT / "shared" / "data" / "NOTICE"
PATRO_LICENSE = ROOT / "packages" / "nepdate-patro" / "LICENSE"
PATRO_NOTICE = ROOT / "packages" / "nepdate-patro" / "NOTICE"

HEADER = "# Generated by scripts/codegen.py. DO NOT EDIT.\n"
MONTH_COUNT = 12
MIN_MONTH_LENGTH = 29
MAX_MONTH_LENGTH = 32
BLOCK_DAYS = 32
LINE_LIMIT = 100
INDENT = "    "


def load_calendar(path: Path | None = None) -> dict[str, Any]:
    """Read and parse the calendar JSON.

    Args:
        path: The calendar JSON file. Defaults to the shared copy.

    Returns:
        The parsed JSON object.

    Raises:
        OSError: The file cannot be read.
        ValueError: The file is not valid JSON or its top level is not an object.
    """
    if path is None:
        path = CALENDAR_JSON
    data = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise ValueError(f"{path} must contain a JSON object")
    return data


def validate_calendar(data: dict[str, Any]) -> None:
    """Check the calendar data has the shape the generator relies on.

    The supported range is one entry per year from ``min_year`` to ``max_year`` inclusive
    (299 years for the shipped data), each with 12 month lengths in 29 through 32.

    Args:
        data: The parsed calendar JSON.

    Raises:
        ValueError: The data does not have the expected shape.
    """
    min_year = data["min_year"]
    max_year = data["max_year"]
    if not isinstance(min_year, int) or not isinstance(max_year, int):
        raise ValueError("min_year and max_year must be integers")
    lengths = data["month_lengths"]
    if not isinstance(lengths, dict):
        raise ValueError("month_lengths must be a JSON object")
    expected = max_year - min_year + 1
    if len(lengths) != expected:
        raise ValueError(f"expected {expected} years, found {len(lengths)}")
    for year in range(min_year, max_year + 1):
        key = str(year)
        if key not in lengths:
            raise ValueError(f"missing month lengths for year {key}")
        months = lengths[key]
        if not isinstance(months, list) or len(months) != MONTH_COUNT:
            raise ValueError(f"year {key} must have {MONTH_COUNT} month lengths")
        for length in months:
            if not isinstance(length, int) or not MIN_MONTH_LENGTH <= length <= MAX_MONTH_LENGTH:
                raise ValueError(
                    f"year {key} has a month length {length!r} outside "
                    f"{MIN_MONTH_LENGTH}..={MAX_MONTH_LENGTH}"
                )


def build_month_lengths(data: dict[str, Any]) -> list[int]:
    """Flatten the month lengths into one value per month, year by year.

    Args:
        data: The validated calendar JSON.

    Returns:
        3588 lengths, one per BS month from 1901-01 through 2199-12.
    """
    min_year = data["min_year"]
    max_year = data["max_year"]
    lengths: list[int] = []
    for year in range(min_year, max_year + 1):
        lengths.extend(data["month_lengths"][str(year)])
    return lengths


def build_month_starts(lengths: list[int]) -> list[int]:
    """Prefix sums of the month lengths.

    Args:
        lengths: One length per BS month.

    Returns:
        3589 serials; entry ``i`` is the serial of month ``i``'s first day and the last
        entry is one past the final day.
    """
    starts = [0]
    for length in lengths:
        starts.append(starts[-1] + length)
    return starts


def build_year_starts(month_starts: list[int]) -> list[int]:
    """Serial of the first day of each year, plus the final sentinel.

    Args:
        month_starts: One serial per month boundary.

    Returns:
        300 serials, one per BS year plus one past the last day.
    """
    return month_starts[::MONTH_COUNT]


def build_bucket(month_starts: list[int]) -> tuple[int, ...]:
    """Build the 32-day block index and prove the two-step bound.

    Entry ``k`` is the month index containing serial ``32 * k``. A month has at least 29
    days, so any serial is at most two months after its block start; the loop below checks
    that for every serial and raises when a block would need more than two steps.

    Args:
        month_starts: One serial per month boundary (3589 entries).

    Returns:
        3413 month indexes, one per 32-day block covering the supported range.

    Raises:
        ValueError: Some serial needs more than two steps from its block start.
    """
    total = month_starts[-1]
    bucket: list[int] = []
    month = 0
    block = 0
    while BLOCK_DAYS * block < total:
        while month_starts[month + 1] <= BLOCK_DAYS * block:
            month += 1
        bucket.append(month)
        block += 1

    for serial in range(total):
        month = bucket[serial >> 5]
        if serial >= month_starts[month + 1]:
            month += 1
        if serial >= month_starts[month + 1]:
            month += 1
        if serial >= month_starts[month + 1]:
            raise ValueError(f"serial {serial} needs more than two bucket steps")
        if not month_starts[month] <= serial < month_starts[month + 1]:
            raise ValueError(f"bucket lookup is wrong at serial {serial}")
    return tuple(bucket)


def build_ordinal_offset(data: dict[str, Any]) -> int:
    """Proleptic Gregorian ordinal of the epoch date.

    Args:
        data: The validated calendar JSON.

    Returns:
        ``date(1844, 4, 11).toordinal()``, which is 673243.
    """
    year, month, day = (int(part) for part in data["epoch"]["ad"].split("-"))
    return datetime.date(year, month, day).toordinal()


def _chunks(values: list[int], size: int) -> list[list[int]]:
    """Split values into fixed-size blocks.

    Args:
        values: The integers to split.
        size: The block size.

    Returns:
        One list per block; the last block may be shorter.
    """
    return [values[start : start + size] for start in range(0, len(values), size)]


def _line(values: list[int], comment: str = "") -> str:
    """Render one wrapped line of integer literals, with an optional comment.

    Args:
        values: The integers on this line.
        comment: An optional ``# ...`` suffix.

    Returns:
        The indented source line, under the 100 column limit.

    Raises:
        ValueError: The line would exceed the column limit.
    """
    line = INDENT + ", ".join(str(value) for value in values) + ","
    if comment:
        line += "  " + comment
    if len(line) > LINE_LIMIT:
        raise ValueError(f"generated line is {len(line)} columns: {line[:40]}...")
    return line


def _month_table(name: str, values: list[int], min_year: int) -> list[str]:
    """Render a per-month table with one line and a ``# year`` comment per BS year.

    Args:
        name: The assignment target.
        values: 3588 values, 12 per year.
        min_year: The first BS year.

    Returns:
        The source lines for the assignment, indented.
    """
    lines = [f"{name} = ("]
    for index, block in enumerate(_chunks(values, MONTH_COUNT)):
        lines.append(_line(block, f"# {min_year + index}"))
    lines.append(")")
    return lines


def _int_table(name: str, values: list[int], per_line: int) -> list[str]:
    """Render a plain tuple of integers, wrapped to stay under 100 columns.

    Args:
        name: The assignment target.
        values: The integers.
        per_line: How many values per line.

    Returns:
        The source lines for the assignment, indented.
    """
    lines = [f"{name} = ("]
    for block in _chunks(values, per_line):
        lines.append(_line(block))
    lines.append(")")
    return lines


def generate_calendar_py(data: dict[str, Any]) -> str:
    """Render the generated ``_calendar.py`` source.

    Args:
        data: The validated calendar JSON.

    Returns:
        The module source with Unix line endings.

    Raises:
        ValueError: The data does not satisfy the two-step bucket bound.
    """
    min_year = data["min_year"]
    max_year = data["max_year"]
    lengths = build_month_lengths(data)
    month_starts = build_month_starts(lengths)
    year_starts = build_year_starts(month_starts)
    bucket = build_bucket(month_starts)
    offset = build_ordinal_offset(data)
    month_start_ord = [serial + offset for serial in month_starts]
    month_year = [min_year + index // MONTH_COUNT for index in range(len(lengths))]
    month_num = [index % MONTH_COUNT + 1 for index in range(len(lengths))]

    lines = [
        HEADER,
        f"MIN_YEAR = {min_year}",
        f"MAX_YEAR = {max_year}",
        f"ORDINAL_OFFSET = {offset}",
        "",
    ]
    lines.append("MONTH_LENGTHS = bytes((")
    for index, block in enumerate(_chunks(lengths, MONTH_COUNT)):
        lines.append(_line(block, f"# {min_year + index}"))
    lines.append("))")
    lines.append("")
    lines.append("MONTH_NUM = bytes((")
    for index, block in enumerate(_chunks(month_num, MONTH_COUNT)):
        lines.append(_line(block, f"# {min_year + index}"))
    lines.append("))")
    lines.append("")
    lines.extend(_month_table("MONTH_YEAR", month_year, min_year))
    lines.append("")
    lines.extend(_int_table("MONTH_START", month_starts, 10))
    lines.append("")
    lines.extend(_int_table("YEAR_START", year_starts, 10))
    lines.append("")
    lines.extend(_int_table("MONTH_START_ORD", month_start_ord, 10))
    lines.append("")
    lines.extend(_int_table("BUCKET", list(bucket), 15))
    return "\n".join(lines) + "\n"


def generated_files(data: dict[str, Any]) -> dict[Path, bytes]:
    """Map every generated file path to the bytes it should hold.

    Args:
        data: The validated calendar JSON.

    Returns:
        Paths keyed to their generated content.
    """
    return {
        CALENDAR_PY: generate_calendar_py(data).encode("utf-8"),
        PATRO_LICENSE: ROOT_LICENSE.read_bytes(),
        PATRO_NOTICE: ROOT_NOTICE.read_bytes(),
    }


def _drifted(path: Path, content: bytes) -> bool:
    try:
        return path.read_bytes() != content
    except OSError:
        return True


def main(argv: list[str] | None = None) -> int:
    """Run the generator.

    Args:
        argv: Command line arguments. Defaults to ``sys.argv[1:]``.

    Returns:
        0 on success, 1 on invalid data or a drift in check mode.
    """
    parser = argparse.ArgumentParser(prog="codegen")
    parser.add_argument("--check", action="store_true", help="exit 1 when a generated file drifted")
    args = parser.parse_args(argv)

    try:
        data = load_calendar()
        validate_calendar(data)
    except (OSError, ValueError) as exc:
        print(f"codegen: {exc}", file=sys.stderr)
        return 1

    files = generated_files(data)
    if args.check:
        drifted = [path for path, content in files.items() if _drifted(path, content)]
        for path in drifted:
            print(f"codegen: {path.relative_to(ROOT)} drifted", file=sys.stderr)
        return 1 if drifted else 0

    for path, content in files.items():
        path.write_bytes(content)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
