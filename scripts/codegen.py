"""Generate the committed, derived files from the read-only shared data.

Standard library only, so it runs wherever Python runs. Plain invocation regenerates every
derived file. ``--check`` exits 1 when any derived file differs from what this script would
write; the CI gate runs it that way.
"""

from __future__ import annotations

import argparse
import datetime
import json
import sys
import unicodedata
from pathlib import Path
from typing import Any, cast

ROOT = Path(__file__).resolve().parent.parent
CALENDAR_JSON = ROOT / "shared" / "data" / "calendar" / "bs-calendar.json"
CALENDAR_PY = ROOT / "src" / "nepdate" / "_calendar.py"
PATRO_DIR = ROOT / "shared" / "data" / "patro"
PATRO_SUMMARY = ROOT / "shared" / "spec" / "vectors" / "patro-summary.json"
PATRO_TABLES_PY = ROOT / "packages" / "nepdate-patro" / "src" / "nepdate_patro" / "_tables.py"
ROOT_LICENSE = ROOT / "LICENSE"
ROOT_NOTICE = ROOT / "shared" / "data" / "NOTICE"
PATRO_LICENSE = ROOT / "packages" / "nepdate-patro" / "LICENSE"
PATRO_NOTICE = ROOT / "packages" / "nepdate-patro" / "NOTICE"

HEADER = "# Generated by scripts/codegen.py. DO NOT EDIT.\n"
MONTH_COUNT = 12
MIN_MONTH_LENGTH = 29
MAX_MONTH_LENGTH = 32
BLOCK_DAYS = 32
LINE_LIMIT = 100
INDENT = "    "
_DATE_PARTS = 3
_MIN_PART_WIDTH = 2
_MAX_TITHI_NAMES = 256
PATRO_SUMMARY_SCHEMA = 1


def load_calendar(path: Path | None = None) -> dict[str, Any]:
    """Read and parse the calendar JSON.

    Args:
        path: The calendar JSON file. Defaults to the shared copy.

    Returns:
        The parsed JSON object.

    Raises:
        OSError: The file cannot be read.
        ValueError: The file is not valid JSON or its top level is not an object.
    """
    if path is None:
        path = CALENDAR_JSON
    data = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise ValueError(f"{path} must contain a JSON object")
    return data


def validate_calendar(data: dict[str, Any]) -> None:
    """Check the calendar data has the shape the generator relies on.

    The supported range is one entry per year from ``min_year`` to ``max_year`` inclusive
    (299 years for the shipped data), each with 12 month lengths in 29 through 32.

    Args:
        data: The parsed calendar JSON.

    Raises:
        ValueError: The data does not have the expected shape.
    """
    min_year = data["min_year"]
    max_year = data["max_year"]
    if not isinstance(min_year, int) or not isinstance(max_year, int):
        raise ValueError("min_year and max_year must be integers")
    lengths = data["month_lengths"]
    if not isinstance(lengths, dict):
        raise ValueError("month_lengths must be a JSON object")
    expected = max_year - min_year + 1
    if len(lengths) != expected:
        raise ValueError(f"expected {expected} years, found {len(lengths)}")
    for year in range(min_year, max_year + 1):
        key = str(year)
        if key not in lengths:
            raise ValueError(f"missing month lengths for year {key}")
        months = lengths[key]
        if not isinstance(months, list) or len(months) != MONTH_COUNT:
            raise ValueError(f"year {key} must have {MONTH_COUNT} month lengths")
        for length in months:
            if not isinstance(length, int) or not MIN_MONTH_LENGTH <= length <= MAX_MONTH_LENGTH:
                raise ValueError(
                    f"year {key} has a month length {length!r} outside "
                    f"{MIN_MONTH_LENGTH}..={MAX_MONTH_LENGTH}"
                )


def build_month_lengths(data: dict[str, Any]) -> list[int]:
    """Flatten the month lengths into one value per month, year by year.

    Args:
        data: The validated calendar JSON.

    Returns:
        3588 lengths, one per BS month from 1901-01 through 2199-12.
    """
    min_year = data["min_year"]
    max_year = data["max_year"]
    lengths: list[int] = []
    for year in range(min_year, max_year + 1):
        lengths.extend(data["month_lengths"][str(year)])
    return lengths


def build_month_starts(lengths: list[int]) -> list[int]:
    """Prefix sums of the month lengths.

    Args:
        lengths: One length per BS month.

    Returns:
        3589 serials; entry ``i`` is the serial of month ``i``'s first day and the last
        entry is one past the final day.
    """
    starts = [0]
    for length in lengths:
        starts.append(starts[-1] + length)
    return starts


def build_year_starts(month_starts: list[int]) -> list[int]:
    """Serial of the first day of each year, plus the final sentinel.

    Args:
        month_starts: One serial per month boundary.

    Returns:
        300 serials, one per BS year plus one past the last day.
    """
    return month_starts[::MONTH_COUNT]


def build_bucket(month_starts: list[int]) -> tuple[int, ...]:
    """Build the 32-day block index and prove the two-step bound.

    Entry ``k`` is the month index containing serial ``32 * k``. A month has at least 29
    days, so any serial is at most two months after its block start; the loop below checks
    that for every serial and raises when a block would need more than two steps.

    Args:
        month_starts: One serial per month boundary (3589 entries).

    Returns:
        3413 month indexes, one per 32-day block covering the supported range.

    Raises:
        ValueError: Some serial needs more than two steps from its block start.
    """
    total = month_starts[-1]
    bucket: list[int] = []
    month = 0
    block = 0
    while BLOCK_DAYS * block < total:
        while month_starts[month + 1] <= BLOCK_DAYS * block:
            month += 1
        bucket.append(month)
        block += 1

    for serial in range(total):
        month = bucket[serial >> 5]
        if serial >= month_starts[month + 1]:
            month += 1
        if serial >= month_starts[month + 1]:
            month += 1
        if serial >= month_starts[month + 1]:
            raise ValueError(f"serial {serial} needs more than two bucket steps")
        if not month_starts[month] <= serial < month_starts[month + 1]:
            raise ValueError(f"bucket lookup is wrong at serial {serial}")
    return tuple(bucket)


def build_ordinal_offset(data: dict[str, Any]) -> int:
    """Proleptic Gregorian ordinal of the epoch date.

    Args:
        data: The validated calendar JSON.

    Returns:
        ``date(1844, 4, 11).toordinal()``, which is 673243.
    """
    year, month, day = (int(part) for part in data["epoch"]["ad"].split("-"))
    return datetime.date(year, month, day).toordinal()


def _chunks(values: list[int], size: int) -> list[list[int]]:
    """Split values into fixed-size blocks.

    Args:
        values: The integers to split.
        size: The block size.

    Returns:
        One list per block; the last block may be shorter.
    """
    return [values[start : start + size] for start in range(0, len(values), size)]


def _line(values: list[int], comment: str = "") -> str:
    """Render one wrapped line of integer literals, with an optional comment.

    Args:
        values: The integers on this line.
        comment: An optional ``# ...`` suffix.

    Returns:
        The indented source line, under the 100 column limit.

    Raises:
        ValueError: The line would exceed the column limit.
    """
    line = INDENT + ", ".join(str(value) for value in values) + ","
    if comment:
        line += "  " + comment
    if len(line) > LINE_LIMIT:
        raise ValueError(f"generated line is {len(line)} columns: {line[:40]}...")
    return line


def _month_table(name: str, values: list[int], min_year: int) -> list[str]:
    """Render a per-month table with one line and a ``# year`` comment per BS year.

    Args:
        name: The assignment target.
        values: 3588 values, 12 per year.
        min_year: The first BS year.

    Returns:
        The source lines for the assignment, indented.
    """
    lines = [f"{name} = ("]
    for index, block in enumerate(_chunks(values, MONTH_COUNT)):
        lines.append(_line(block, f"# {min_year + index}"))
    lines.append(")")
    return lines


def _int_table(name: str, values: list[int], per_line: int) -> list[str]:
    """Render a plain tuple of integers, wrapped to stay under 100 columns.

    Args:
        name: The assignment target.
        values: The integers.
        per_line: How many values per line.

    Returns:
        The source lines for the assignment, indented.
    """
    lines = [f"{name} = ("]
    for block in _chunks(values, per_line):
        lines.append(_line(block))
    lines.append(")")
    return lines


def generate_calendar_py(data: dict[str, Any]) -> str:
    """Render the generated ``_calendar.py`` source.

    Args:
        data: The validated calendar JSON.

    Returns:
        The module source with Unix line endings.

    Raises:
        ValueError: The data does not satisfy the two-step bucket bound.
    """
    min_year = data["min_year"]
    max_year = data["max_year"]
    lengths = build_month_lengths(data)
    month_starts = build_month_starts(lengths)
    year_starts = build_year_starts(month_starts)
    bucket = build_bucket(month_starts)
    offset = build_ordinal_offset(data)
    month_start_ord = [serial + offset for serial in month_starts]
    month_year = [min_year + index // MONTH_COUNT for index in range(len(lengths))]
    month_num = [index % MONTH_COUNT + 1 for index in range(len(lengths))]

    lines = [
        HEADER,
        f"MIN_YEAR = {min_year}",
        f"MAX_YEAR = {max_year}",
        f"ORDINAL_OFFSET = {offset}",
        "",
    ]
    lines.append("MONTH_LENGTHS = bytes((")
    for index, block in enumerate(_chunks(lengths, MONTH_COUNT)):
        lines.append(_line(block, f"# {min_year + index}"))
    lines.append("))")
    lines.append("")
    lines.append("MONTH_NUM = bytes((")
    for index, block in enumerate(_chunks(month_num, MONTH_COUNT)):
        lines.append(_line(block, f"# {min_year + index}"))
    lines.append("))")
    lines.append("")
    lines.extend(_month_table("MONTH_YEAR", month_year, min_year))
    lines.append("")
    lines.extend(_int_table("MONTH_START", month_starts, 10))
    lines.append("")
    lines.extend(_int_table("YEAR_START", year_starts, 10))
    lines.append("")
    lines.extend(_int_table("MONTH_START_ORD", month_start_ord, 10))
    lines.append("")
    lines.extend(_int_table("BUCKET", list(bucket), 15))
    return "\n".join(lines) + "\n"


def _validate_patro_name(pair: dict[str, Any], date: str, what: str) -> None:
    """Check one ``np``/``en`` pair has two non-empty strings.

    Args:
        pair: The JSON object with the two strings.
        date: The day the pair belongs to, for the error message.
        what: ``"tithi"`` or ``"event"``, for the error message.

    Raises:
        ValueError: A field is missing or empty.
    """
    for key in ("np", "en"):
        value = pair.get(key)
        if not isinstance(value, str) or not value:
            raise ValueError(f"{date}: {what} has an empty or missing {key!r}")


def _validate_patro_day(date: str, info: dict[str, Any]) -> None:
    """Check one patro day has the shape PATRO §1 describes.

    Args:
        date: The BS date text.
        info: The day's JSON object.

    Raises:
        ValueError: A field has the wrong type.
    """
    if not isinstance(info, dict):
        raise ValueError(f"{date}: day data must be a JSON object")
    if "tithi" in info:
        tithi = info["tithi"]
        if not isinstance(tithi, dict):
            raise ValueError(f"{date}: tithi must be a JSON object")
        _validate_patro_name(tithi, date, "tithi")
    holiday = info.get("holiday", False)
    if not isinstance(holiday, bool):
        raise ValueError(f"{date}: holiday must be true or false")
    events = info.get("events", [])
    if not isinstance(events, list):
        raise ValueError(f"{date}: events must be a JSON list")
    for event in events:
        if not isinstance(event, dict):
            raise ValueError(f"{date}: every event must be a JSON object")
        _validate_patro_name(event, date, "event")


def load_patro(directory: Path | None = None) -> dict[str, dict[str, Any]]:
    """Read every patro JSON file into one day map.

    Args:
        directory: The patro data directory. Defaults to the shared copy.

    Returns:
        The BS date text keyed to its parsed day object.

    Raises:
        OSError: A file cannot be read.
        ValueError: A file or day does not have the expected shape, a day appears twice, or
            there is no day at all.
    """
    if directory is None:
        directory = PATRO_DIR
    days: dict[str, dict[str, Any]] = {}
    for path in sorted(directory.glob("*.json")):
        raw = json.loads(path.read_text(encoding="utf-8"))
        if not isinstance(raw, dict):
            raise ValueError(f"{path.name} must contain a JSON object")
        if raw.get("schema") != 1:
            raise ValueError(f"{path.name} has an unsupported schema")
        year = raw.get("year")
        if not isinstance(year, int):
            raise ValueError(f"{path.name} must have an integer year")
        file_days = raw.get("days")
        if not isinstance(file_days, dict):
            raise ValueError(f"{path.name} must have a days object")
        prefix = f"{year:04d}-"
        for date, info in cast(dict[str, Any], file_days).items():
            if not isinstance(date, str) or not date.startswith(prefix):
                raise ValueError(f"{path.name} has a day outside its year: {date!r}")
            if date in days:
                raise ValueError(f"duplicate patro day {date}")
            _validate_patro_day(date, info)
            days[date] = info
    if not days:
        raise ValueError(f"no patro data in {directory}")
    return days


def _path_text(path: Path) -> str:
    """Render a path for an error message, relative to the repository when possible.

    Args:
        path: The path to render.

    Returns:
        The repository-relative POSIX path, or the full path when it lies outside the
        repository.
    """
    try:
        return path.relative_to(ROOT).as_posix()
    except ValueError:
        return str(path)


def load_patro_summary(path: Path | None = None) -> dict[str, Any]:
    """Read the hub's patro summary, the counts every port reads.

    Args:
        path: The summary JSON file. Defaults to the shared copy.

    Returns:
        The parsed summary object.

    Raises:
        ValueError: The file is missing, is not valid JSON, or is not a schema 1 object.
    """
    if path is None:
        path = PATRO_SUMMARY
    try:
        raw = path.read_text(encoding="utf-8")
    except OSError as exc:
        raise ValueError(
            f"{_path_text(path)} is missing; resync shared/ from the hub before running codegen"
        ) from exc
    try:
        summary = json.loads(raw)
    except json.JSONDecodeError as exc:
        raise ValueError(f"{_path_text(path)} is not valid JSON: {exc}") from exc
    if not isinstance(summary, dict):
        raise ValueError(f"{_path_text(path)} must contain a JSON object")
    if summary.get("schema") != PATRO_SUMMARY_SCHEMA:
        raise ValueError(f"{_path_text(path)} has an unsupported schema")
    return summary


def _date_parts(text: str) -> tuple[int, int, int]:
    """Split a canonical ``YYYY-MM-DD`` BS date.

    Args:
        text: The date text.

    Returns:
        The year, month and day.

    Raises:
        ValueError: The text is not a canonical padded date.
    """
    parts = text.split("-")
    if len(parts) != _DATE_PARTS or any(len(part) < _MIN_PART_WIDTH for part in parts):
        raise ValueError(f"invalid patro date {text!r}")
    year = int(parts[0])
    month = int(parts[1])
    day = int(parts[2])
    if f"{year:04d}-{month:02d}-{day:02d}" != text:
        raise ValueError(f"invalid patro date {text!r}")
    return year, month, day


def _patro_ordinals(
    days: dict[str, dict[str, Any]], calendar: dict[str, Any]
) -> dict[int, dict[str, Any]]:
    """Map every BS day to its proleptic Gregorian ordinal.

    Args:
        days: The parsed patro day map.
        calendar: The validated calendar JSON.

    Returns:
        The ordinal keyed to the day object.

    Raises:
        ValueError: A date is invalid or outside the calendar range.
    """
    lengths = build_month_lengths(calendar)
    starts = build_month_starts(lengths)
    offset = build_ordinal_offset(calendar)
    min_year = calendar["min_year"]
    max_year = calendar["max_year"]
    by_ordinal: dict[int, dict[str, Any]] = {}
    for text in sorted(days):
        year, month, day = _date_parts(text)
        if not min_year <= year <= max_year:
            raise ValueError(f"{text}: outside the calendar range")
        if not 1 <= month <= MONTH_COUNT:
            raise ValueError(f"{text}: month outside 1..12")
        index = (year - min_year) * MONTH_COUNT + (month - 1)
        if not 1 <= day <= lengths[index]:
            raise ValueError(f"{text}: day outside the month")
        ordinal = offset + starts[index] + day - 1
        if ordinal in by_ordinal:
            raise ValueError(f"{text}: duplicate ordinal")
        by_ordinal[ordinal] = days[text]
    if not by_ordinal:
        raise ValueError("no patro days")
    return by_ordinal


def _tithi_tables(
    by_ordinal: dict[int, dict[str, Any]],
) -> tuple[int, bytes, tuple[tuple[str, str], ...]]:
    """Build the tithi range, one-byte index and name table.

    Args:
        by_ordinal: The patro days keyed by ordinal.

    Returns:
        The first tithi ordinal, the index bytes and the name pairs.

    Raises:
        ValueError: A tithi is missing inside its range or there are more than 256 names.
    """
    tithi_ordinals = [ordinal for ordinal, info in by_ordinal.items() if "tithi" in info]
    if not tithi_ordinals:
        raise ValueError("no tithi data")
    first = min(tithi_ordinals)
    last = max(tithi_ordinals)
    index = bytearray()
    names: list[tuple[str, str]] = []
    lookup: dict[tuple[str, str], int] = {}
    for ordinal in range(first, last + 1):
        info = by_ordinal.get(ordinal)
        if info is None or "tithi" not in info:
            raise ValueError(f"missing tithi at ordinal {ordinal}")
        pair = (str(info["tithi"]["np"]), str(info["tithi"]["en"]))
        found = lookup.get(pair)
        if found is None:
            found = len(names)
            if found >= _MAX_TITHI_NAMES:
                raise ValueError(f"more than {_MAX_TITHI_NAMES} tithi names")
            lookup[pair] = found
            names.append(pair)
        index.append(found)
    return first, bytes(index), tuple(names)


def _event_tables(
    by_ordinal: dict[int, dict[str, Any]],
) -> tuple[
    tuple[int, ...],
    tuple[tuple[int, int], ...],
    tuple[int, ...],
    tuple[tuple[str, str], ...],
]:
    """Build the event days, spans, ids and deduplicated name table.

    Args:
        by_ordinal: The patro days keyed by ordinal.

    Returns:
        The event days, spans, id list and name pairs.
    """
    names: list[tuple[str, str]] = []
    lookup: dict[tuple[str, str], int] = {}
    event_days: list[int] = []
    event_spans: list[tuple[int, int]] = []
    event_ids: list[int] = []
    for ordinal in sorted(by_ordinal):
        events = by_ordinal[ordinal].get("events", [])
        if not events:
            continue
        start = len(event_ids)
        for event in events:
            pair = (str(event["np"]), str(event["en"]))
            found = lookup.get(pair)
            if found is None:
                found = len(names)
                lookup[pair] = found
                names.append(pair)
            event_ids.append(found)
        event_days.append(ordinal)
        event_spans.append((start, len(event_ids)))
    return tuple(event_days), tuple(event_spans), tuple(event_ids), tuple(names)


def build_patro_tables(days: dict[str, dict[str, Any]], calendar: dict[str, Any]) -> dict[str, Any]:
    """Compile the day map into the compact tables of ADR-0002 §6.

    Args:
        days: The parsed patro day map.
        calendar: The validated calendar JSON, used to convert BS dates to ordinals.

    Returns:
        The table dictionary, keyed by the names ``_tables.py`` uses.

    Raises:
        ValueError: A date is invalid, a tithi is missing inside its range, or a table
            would not fit its compact representation.
    """
    by_ordinal = _patro_ordinals(days, calendar)
    tithi_first, tithi_index, tithi_names = _tithi_tables(by_ordinal)
    holidays = tuple(
        ordinal for ordinal in sorted(by_ordinal) if by_ordinal[ordinal].get("holiday", False)
    )
    event_days, event_spans, event_ids, names = _event_tables(by_ordinal)
    return {
        "coverage_first": min(by_ordinal),
        "coverage_last": max(by_ordinal),
        "tithi_first": tithi_first,
        "tithi_index": tithi_index,
        "tithi_names": tithi_names,
        "holidays": holidays,
        "event_days": event_days,
        "event_spans": event_spans,
        "event_ids": event_ids,
        "names": names,
    }


def patro_counts(
    days: dict[str, dict[str, Any]],
    tables: dict[str, Any],
    calendar: dict[str, Any],
) -> dict[str, Any]:
    """Derive every field of the patro summary from the loaded days and the built tables.

    Args:
        days: The parsed patro day map.
        tables: The output of :func:`build_patro_tables`.
        calendar: The validated calendar JSON.

    Returns:
        The summary fields keyed to their values. ``first_serial`` and ``last_serial`` are
        ALGORITHM serials, so ``days`` is the span from one to the other inclusive.
    """
    offset = build_ordinal_offset(calendar)
    first_day = min(days)
    last_day = max(days)
    tithi_days = [text for text, info in days.items() if "tithi" in info]
    names = set(tables["tithi_names"]) | set(tables["names"])
    name_bytes = sum(len(np.encode("utf-8")) + len(en.encode("utf-8")) for np, en in names)
    first_serial = tables["coverage_first"] - offset
    last_serial = tables["coverage_last"] - offset
    return {
        "first_year": int(first_day[:4]),
        "last_year": int(last_day[:4]),
        "first_day": first_day,
        "last_day": last_day,
        "first_serial": first_serial,
        "last_serial": last_serial,
        "days": last_serial - first_serial + 1,
        "tithi_first_day": min(tithi_days),
        "tithi_last_day": max(tithi_days),
        "tithi_first_serial": tables["tithi_first"] - offset,
        "tithi_days": len(tables["tithi_index"]),
        "tithi_names": len(tables["tithi_names"]),
        "holidays": len(tables["holidays"]),
        "event_days": len(tables["event_days"]),
        "events": len(tables["event_ids"]),
        "event_names": len(tables["names"]),
        "names": len(names),
        "name_bytes": name_bytes,
    }


def validate_patro_summary(
    days: dict[str, dict[str, Any]],
    tables: dict[str, Any],
    calendar: dict[str, Any],
    summary: dict[str, Any],
) -> None:
    """Check the built patro tables against the hub's summary file.

    The generator pins no count of its own: every value comes from the data. This check keeps
    the data and the summary in step, so a stale summary fails instead of being copied.

    Args:
        days: The parsed patro day map.
        tables: The output of :func:`build_patro_tables`.
        calendar: The validated calendar JSON.
        summary: The parsed patro summary.

    Raises:
        ValueError: A summary field is missing or differs from the data.
    """
    derived = patro_counts(days, tables, calendar)
    missing = [field for field in derived if field not in summary]
    if missing:
        raise ValueError(f"patro summary is missing {', '.join(missing)}")
    for field, actual in derived.items():
        expected = summary[field]
        if expected != actual:
            raise ValueError(
                f"patro summary {field} is {expected!r}, but the data gives {actual!r}"
            )


def source_text(text: str) -> str:
    r"""Render a string as a Python source literal.

    Args:
        text: The string value.

    Returns:
        The literal, with quotes and backslashes escaped and every invisible character
        written as a ``\N{...}`` escape.
    """
    pieces = ["'"]
    for char in text:
        if char == "'":
            pieces.append("\\'")
        elif char == "\\":
            pieces.append("\\\\")
        elif char == "\n":
            pieces.append("\\n")
        elif char == "\r":
            pieces.append("\\r")
        elif char == "\t":
            pieces.append("\\t")
        elif char == "\u2013":
            pieces.append("\\N{EN DASH}")
        elif unicodedata.category(char) in ("Cf", "Cc"):
            name = unicodedata.name(char, "")
            pieces.append(f"\\N{{{name}}}" if name else f"\\u{ord(char):04x}")
        else:
            pieces.append(char)
    pieces.append("'")
    return "".join(pieces)


def _pair_lines(pair: tuple[str, str]) -> list[str]:
    """Render one ``(np, en)`` pair, wrapped when it would pass the column limit.

    Args:
        pair: The two strings.

    Returns:
        The source lines for the tuple entry.

    Raises:
        ValueError: One string alone is too long to render under the limit.
    """
    left = source_text(pair[0])
    right = source_text(pair[1])
    line = f"{INDENT}({left}, {right}),"
    if len(line) <= LINE_LIMIT:
        return [line]
    if len(left) > LINE_LIMIT - len(INDENT) * 2 or len(right) > LINE_LIMIT - len(INDENT) * 2:
        raise ValueError(f"generated string is too long: {pair[0][:20]!r}")
    return [
        f"{INDENT}(",
        f"{INDENT}{INDENT}{left},",
        f"{INDENT}{INDENT}{right},",
        f"{INDENT}),",
    ]


def _pairs_table(name: str, pairs: tuple[tuple[str, str], ...]) -> list[str]:
    """Render a tuple of string pairs.

    Args:
        name: The assignment target.
        pairs: The pairs to render.

    Returns:
        The source lines for the assignment.
    """
    lines = [f"{name} = ("]
    for pair in pairs:
        lines.extend(_pair_lines(pair))
    lines.append(")")
    return lines


def _bytes_table(name: str, values: bytes, per_line: int) -> list[str]:
    """Render a ``bytes((...))`` table.

    Args:
        name: The assignment target.
        values: The bytes.
        per_line: How many values per line.

    Returns:
        The source lines for the assignment.
    """
    lines = [f"{name} = bytes(("]
    for block in _chunks(list(values), per_line):
        lines.append(_line(block))
    lines.append("))")
    return lines


def _spans_table(name: str, spans: tuple[tuple[int, int], ...]) -> list[str]:
    """Render a tuple of ``(start, end)`` spans.

    Args:
        name: The assignment target.
        spans: The spans.

    Returns:
        The source lines for the assignment.

    Raises:
        ValueError: A line would pass the column limit.
    """
    lines = [f"{name} = ("]
    for start, end in spans:
        line = f"{INDENT}({start}, {end}),"
        if len(line) > LINE_LIMIT:
            raise ValueError(f"generated span line is {len(line)} columns")
        lines.append(line)
    lines.append(")")
    return lines


def generate_patro_py(tables: dict[str, Any]) -> str:
    """Render the generated ``_tables.py`` source.

    Args:
        tables: The output of :func:`build_patro_tables`.

    Returns:
        The module source with Unix line endings.
    """
    lines = [
        HEADER,
        f"COVERAGE_FIRST = {tables['coverage_first']}",
        f"COVERAGE_LAST = {tables['coverage_last']}",
        f"TITHI_FIRST = {tables['tithi_first']}",
        "",
    ]
    lines.extend(_bytes_table("TITHI_INDEX", tables["tithi_index"], 20))
    lines.append("")
    lines.extend(_pairs_table("TITHI_NAMES", tables["tithi_names"]))
    lines.append("")
    lines.extend(_int_table("HOLIDAYS", list(tables["holidays"]), 10))
    lines.append("")
    lines.extend(_int_table("EVENT_DAYS", list(tables["event_days"]), 10))
    lines.append("")
    lines.extend(_spans_table("EVENT_SPANS", tables["event_spans"]))
    lines.append("")
    lines.extend(_int_table("EVENT_IDS", list(tables["event_ids"]), 15))
    lines.append("")
    lines.extend(_pairs_table("NAMES", tables["names"]))
    return "\n".join(lines) + "\n"


def generated_files(
    data: dict[str, Any],
    patro_days: dict[str, dict[str, Any]],
    summary: dict[str, Any],
) -> dict[Path, bytes]:
    """Map every generated file path to the bytes it should hold.

    Args:
        data: The validated calendar JSON.
        patro_days: The loaded patro day map.
        summary: The parsed patro summary.

    Returns:
        Paths keyed to their generated content.

    Raises:
        ValueError: The patro tables cannot be built or disagree with the summary.
    """
    tables = build_patro_tables(patro_days, data)
    validate_patro_summary(patro_days, tables, data, summary)
    return {
        CALENDAR_PY: generate_calendar_py(data).encode("utf-8"),
        PATRO_TABLES_PY: generate_patro_py(tables).encode("utf-8"),
        PATRO_LICENSE: ROOT_LICENSE.read_bytes(),
        PATRO_NOTICE: ROOT_NOTICE.read_bytes(),
    }


def _drifted(path: Path, content: bytes) -> bool:
    try:
        return path.read_bytes() != content
    except OSError:
        return True


def main(argv: list[str] | None = None) -> int:
    """Run the generator.

    Args:
        argv: Command line arguments. Defaults to ``sys.argv[1:]``.

    Returns:
        0 on success, 1 on invalid data or a drift in check mode.
    """
    parser = argparse.ArgumentParser(prog="codegen")
    parser.add_argument("--check", action="store_true", help="exit 1 when a generated file drifted")
    args = parser.parse_args(argv)

    try:
        data = load_calendar()
        validate_calendar(data)
        patro_days = load_patro()
        summary = load_patro_summary()
        files = generated_files(data, patro_days, summary)
    except (OSError, ValueError) as exc:
        print(f"codegen: {exc}", file=sys.stderr)
        return 1

    if args.check:
        drifted = [path for path, content in files.items() if _drifted(path, content)]
        for path in drifted:
            print(f"codegen: {path.relative_to(ROOT)} drifted", file=sys.stderr)
        return 1 if drifted else 0

    for path, content in files.items():
        path.write_bytes(content)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
