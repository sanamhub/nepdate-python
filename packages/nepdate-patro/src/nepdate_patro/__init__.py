"""Tithi, public holidays and events for the Nepali calendar.

A separate distribution from the core ``nepdate`` package (ADR-0001). The public surface is
``nepdate_patro.__all__``, documented in ``docs/API.md``. The tables in ``_tables.py`` are
generated by ``scripts/codegen.py``; this module turns them into one prebuilt ``CalendarInfo``
per coverage day (ADR-0002 §6).
"""

from __future__ import annotations

from nepdate import DateRange, Lang, NepaliDate

from ._tables import (
    COVERAGE_FIRST,
    COVERAGE_LAST,
    EVENT_DAYS,
    EVENT_IDS,
    EVENT_SPANS,
    HOLIDAYS,
    NAMES,
    TITHI_FIRST,
    TITHI_INDEX,
    TITHI_NAMES,
)

# `typing` would add modules to `import nepdate_patro` (the import gate); the constant is enough
# for the type checker, as in the core.
TYPE_CHECKING = False
if TYPE_CHECKING:
    from collections.abc import Iterator

__all__ = [
    "CalendarInfo",
    "Event",
    "Tithi",
    "coverage",
    "info",
    "public_holidays",
]


class Tithi:
    """One tithi (lunar day) in Nepali and English.

    An immutable value: equal tithis compare and hash equal. It is written by hand, not with
    ``dataclasses``, because that module would break the import gate (ADR-0002 §7).
    """

    __slots__ = ("en", "np")

    np: str
    en: str

    def __init__(self, np: str, en: str) -> None:
        """Build a tithi from its two labels.

        Args:
            np: The Nepali label.
            en: The English label.
        """
        set_field = object.__setattr__
        set_field(self, "np", np)
        set_field(self, "en", en)

    def label(self, lang: Lang = Lang.EN) -> str:
        """The label in ``lang``: ``np`` for Nepali, ``en`` for English."""
        if lang is Lang.NE:
            return self.np
        return self.en

    def _key(self) -> tuple[str, str]:
        return (self.np, self.en)

    def __eq__(self, other: object) -> bool:
        """Return whether ``other`` is a tithi with the same two labels."""
        if not isinstance(other, Tithi):
            return NotImplemented
        return self._key() == other._key()

    def __hash__(self) -> int:
        """Return a hash of the two labels."""
        return hash(self._key())

    def __repr__(self) -> str:
        """Return the constructor-style representation."""
        return f"Tithi(np={self.np!r}, en={self.en!r})"

    def __setattr__(self, name: str, value: object) -> None:
        """Refuse assignment; a tithi is immutable."""
        raise AttributeError(f"Tithi is immutable; cannot set {name!r}")

    def __delattr__(self, name: str) -> None:
        """Refuse deletion; a tithi is immutable."""
        raise AttributeError(f"Tithi is immutable; cannot delete {name!r}")


