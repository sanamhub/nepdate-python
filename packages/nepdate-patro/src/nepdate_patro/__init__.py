class CalendarInfo:
    """The patro data for one day: tithi, holiday flag and ordered events.

    An immutable value, written by hand for the same reason as :class:`Tithi`.
    """

    __slots__ = ("events", "is_public_holiday", "tithi")

    tithi: Tithi | None
    is_public_holiday: bool
    events: tuple[Event, ...]

    def __init__(
        self, tithi: Tithi | None, is_public_holiday: bool, events: tuple[Event, ...]
    ) -> None:
        """Build one day's info.

        Args:
            tithi: The tithi, or None when the day has none.
            is_public_holiday: Whether the day is a gazetted public holiday.
            events: The events in file (display) order.
        """
        set_field = object.__setattr__
        set_field(self, "tithi", tithi)
        set_field(self, "is_public_holiday", is_public_holiday)
        set_field(self, "events", tuple(events))

    def _key(self) -> tuple[Tithi | None, bool, tuple[Event, ...]]:
        return (self.tithi, self.is_public_holiday, self.events)

    def __eq__(self, other: object) -> bool:
        """Return whether ``other`` is the same day's info."""
        if not isinstance(other, CalendarInfo):
            return NotImplemented
        return self._key() == other._key()

    def __hash__(self) -> int:
        """Return a hash of the three fields."""
        return hash(self._key())

    def __repr__(self) -> str:
        """Return the constructor-style representation."""
        return (
            f"CalendarInfo(tithi={self.tithi!r}, is_public_holiday={self.is_public_holiday!r}, "
            f"events={self.events!r})"
        )

    def __setattr__(self, name: str, value: object) -> None:
        """Refuse assignment; the day's info is immutable."""
        raise AttributeError(f"CalendarInfo is immutable; cannot set {name!r}")

    def __delattr__(self, name: str) -> None:
        """Refuse deletion; the day's info is immutable."""
        raise AttributeError(f"CalendarInfo is immutable; cannot delete {name!r}")


_TITHI_OBJECTS = tuple(Tithi(np, en) for np, en in TITHI_NAMES)
_EVENT_OBJECTS = tuple(Event(np, en) for np, en in NAMES)
_EMPTY = CalendarInfo(None, False, ())
_TITHI_END = TITHI_FIRST + len(TITHI_INDEX)


def _build_day_info() -> tuple[CalendarInfo, ...]:
    """Build one immutable ``CalendarInfo`` per coverage day from the compact tables.

    Returns:
        ``COVERAGE_LAST - COVERAGE_FIRST + 1`` entries, sharing tithi and event objects and
        using ``_EMPTY`` for days with no data.
    """
    holiday_set = frozenset(HOLIDAYS)
    event_index = {ordinal: index for index, ordinal in enumerate(EVENT_DAYS)}
    day_info: list[CalendarInfo] = []
    for ordinal in range(COVERAGE_FIRST, COVERAGE_LAST + 1):
        if TITHI_FIRST <= ordinal < _TITHI_END:
            tithi = _TITHI_OBJECTS[TITHI_INDEX[ordinal - TITHI_FIRST]]
        else:
            tithi = None
        holiday = ordinal in holiday_set
        found = event_index.get(ordinal)
        if found is None:
            events: tuple[Event, ...] = ()
        else:
            start, end = EVENT_SPANS[found]
            events = tuple(_EVENT_OBJECTS[EVENT_IDS[i]] for i in range(start, end))
        if tithi is None and not holiday and not events:
            day_info.append(_EMPTY)
        else:
            day_info.append(CalendarInfo(tithi, holiday, events))
    return tuple(day_info)


_DAY_INFO = _build_day_info()
_COVERAGE = DateRange(
    NepaliDate.from_ordinal(COVERAGE_FIRST), NepaliDate.from_ordinal(COVERAGE_LAST)
)


def info(d: NepaliDate) -> CalendarInfo:
    """The patro data for ``d``, or the shared empty object outside coverage (PATRO §2).

    Args:
        d: The BS date to look up.

    Returns:
        The prebuilt ``CalendarInfo`` of the day. The call builds no object.
    """
    index = d.to_ordinal() - COVERAGE_FIRST
    if 0 <= index < len(_DAY_INFO):
        return _DAY_INFO[index]
    return _EMPTY


def coverage() -> DateRange:
    """The smallest BS range containing every day with metadata (PATRO §2)."""
    return _COVERAGE


def public_holidays() -> Iterator[NepaliDate]:
    """Yield every public holiday in ascending order."""
    for ordinal in HOLIDAYS:
        yield NepaliDate.from_ordinal(ordinal)
